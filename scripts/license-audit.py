#!/usr/bin/env python3
"""List the licence of every crate Facet links on Linux and flag anything not on the allow-list.
Writes THIRD-PARTY-LICENSES.md when run with --write. Exit 1 if an unreviewed licence is found."""
import json, subprocess, sys, re, collections

meta = json.loads(subprocess.run(["cargo", "metadata", "--format-version", "1", "--filter-platform", "x86_64-unknown-linux-gnu"], capture_output=True, text=True, check=True).stdout)
resolve = {n["id"]: n for n in meta["resolve"]["nodes"]}
pkgs = {p["id"]: p for p in meta["packages"]}
# Only crates reachable from the shipped binaries, via normal (non-dev, non-build-only-host) dependency edges.
roots = [p["id"] for p in meta["packages"] if p["name"] in ("facet-app", "facet-cli")]
seen, stack = set(), list(roots)
while stack:
    i = stack.pop()
    if i in seen: continue
    seen.add(i)
    for d in resolve[i]["deps"]:
        if any(k["kind"] in (None, "build") for k in d["dep_kinds"]):
            stack.append(d["pkg"])

ALLOW = re.compile(r"MIT|Apache-2\.0|BSD|ISC|Zlib|Unicode|CC0|MPL-2\.0|0BSD|BSL-1\.0|OFL|Unlicense|LGPL|bzip2", re.I)
COPYLEFT = re.compile(r"(?<!L)GPL|AGPL", re.I)
by_license = collections.defaultdict(list)
problems = []
for i in sorted(seen, key=lambda i: pkgs[i]["name"]):
    p = pkgs[i]
    if p["name"].startswith("facet-"): continue
    lic = p.get("license") or ("(see license-file)" if p.get("license_file") else "UNKNOWN")
    by_license[lic].append(f'{p["name"]} {p["version"]}')
    src = p.get("source") or ""
    if COPYLEFT.search(lic) and not re.search(r"MIT|Apache", lic):
        problems.append(f'{p["name"]} {p["version"]}: {lic}')
    elif lic == "UNKNOWN" or not ALLOW.search(lic):
        problems.append(f'{p["name"]} {p["version"]}: {lic} (needs review)')
total = sum(len(v) for v in by_license.values())
print(f"{total} third-party crates in the shipped dependency graph")
for lic, names in sorted(by_license.items(), key=lambda kv: -len(kv[1]))[:14]:
    print(f"  {len(names):4}  {lic}")
git = [f'{pkgs[i]["name"]} {pkgs[i]["version"]} ({pkgs[i].get("license")}) {pkgs[i]["source"]}' for i in seen if (pkgs[i].get("source") or "").startswith("git+")]
print(f"\n{len(git)} crates come from git sources (Zed's GPUI revision and a few forks):")
for g in sorted(git): print("  ", g[:140])
if problems:
    print("\nNEEDS ATTENTION:"); [print("  ", x) for x in problems]
if "--write" in sys.argv:
    with open("THIRD-PARTY-LICENSES.md", "w") as f:
        f.write("# Third-party licences\n\nGenerated by `scripts/license-audit.py` from `cargo metadata` (Linux, shipped binaries only).\nFacet itself is MIT OR Apache-2.0. Bundled assets: IBM Plex Sans and Lilex (SIL OFL 1.1; see `assets/fonts/`), Lucide icons (ISC; see `assets/icons/LICENSE`).\n\n")
        for lic, names in sorted(by_license.items()):
            f.write(f"## {lic}\n\n" + ", ".join(names) + "\n\n")
sys.exit(1 if problems else 0)
